@dataclass(frozen=True)
class Source:
    """オープンデータ 1 件の取得定義。fetch.py が参照する。"""

    key: str
    label: str
    url: str
    kind: str  # "csv" | "shp" | "geojson" | "api" | "excel" | "manual"
    license: str
    note: str = ""
    api_key_env: str | None = None
    params: dict = field(default_factory=dict)

    # **著作権表示（作者名）。** CC BY が最初に求めるものだが、`label` でも
    # `license` でも代わりにならない——`label` はデータの名前、`license` は
    # 条件であって、**どちらも「誰の著作物か」を言っていない**。
    # 経由したカタログの名前を書かないこと（公共施設一覧でそれをやった）。
    rights_holder: str = ""

    # **ライセンス条文の URL。** 事務局の案内が挙げている 4 点目。
    # 名前の付いたライセンスを名乗るなら、条文の場所まで出す。
    # 空にしてよいのは「名前の付いたライセンスではない」ものだけで、
    # いま該当するのは環境局の騒音（口頭の許諾）と手集計の 2 件。
    license_url: str = ""

    # --- ここから下は「画面に出すため」の欄 ---
    #
    # レジストリに載っているだけでは、その出典を実際に使ったことにならない。
    # 実際 16 件のうち 5 件は検討しただけで使っていない（ODPT・不動産情報
    # ライブラリ・鉄道騒音・手帳交付状況・既存スペース）。**画面が出典一覧を
    # 出すなら、使っていないものを混ぜて数を稼いではいけない。**
    layer: str | None = None  # 生成に使ったレイヤー名。None = 未使用
    vintage: str = ""  # 年次。年がそろっていないこと自体が課題（issues.md C1）

    # **URL が 200 を返すことは、そこに使ったデータがある証拠にならない。**
    # 列名の決め打ちと同じ壊れ方をした——N03 は `-v3_1` のページが生きているが
    # 最新が 2023 年版で、実際に使った `N03-20240101_13` は別ページ
    # （`-2024`）にあった。P29 も同じで、リンク先には 2013 年版しか無い。
    # **どちらもリンクは開ける**ので、押して確かめても気付けない。
    # 実際に読み込んだファイル名をここに書き、tools/link_check.py が
    # 「リンク先のページにその名前が載っていること」まで検査する。
    # 空文字は「ページ内から機械的に確かめる手掛かりが無い」の意（API・検索）。
    #
    # **複数書ける**（tuple）。1 ページから複数年度・複数ファイルを取る出典が
    # あるため——騒音の常時監視は令和元〜5年度の 5 年分を使っており、
    # 1 年度だけ照合するとページが改組されて古い年度が落ちても通ってしまう。
    # 書いたものは**すべて**ページ内にあることを求める。
    file_hint: str | tuple[str, ...] = ""

    # **なぜ機械的に確かめられないのか。**
    #
    # `file_hint` が空なだけだと、検査の出力は「file_hint が空」しか言えない。
    # **「まだ書いていない」と「書けない」が同じ見た目になる**——実際
    # 都教委の在籍者数は「一覧ページにファイル名は出ていない」という
    # **確かめずに書いた理由**で空のままになっており、ページにはその名前が
    # 載っていた（2026-08-07 に是正）。理由を書く欄を分けておけば、
    # 空欄は「未着手」だけを意味するようになる。
    #
    # ここに書くのは**そのページで試して駄目だった理由**に限る。
    # 推測を書くと、また確かめずに書いた理由が居座る。
    unverifiable: str = ""

    # **この出典が過去に名乗っていた label。**
    #
    # `data/processed/*.geojson` の `source` 列は、正規化した時点の label を
    # 焼き付けたスナップショットである（`fetch.py` が `SOURCES[...].label` を
    # 書き込む）。つまり **label を直しても、既に正規化済みのデータは古い名前を
    # 持ち回る**。実際 2026-08-04 に公共施設一覧の label を直したところ、
    # 出典一覧は新しい名前・施設をクリックしたときの出典は古い名前、という
    # **同じ出典が画面で 2 つの名前を名乗る**状態になった
    # （施設一覧を出すようにして初めて見えた）。
    #
    # 30 本のファイルを正規化し直すのが本筋だが、**名前を直すたびに
    # 再正規化が要るのはおかしい**——出典の名前は config が唯一の出所である。
    # ここに旧 label を残し、配信時に現在の label へ寄せる（build.py）。
    aliases: tuple[str, ...] = ()

    @property
    def file_hints(self) -> tuple[str, ...]:
        """file_hint を必ずタプルで返す（str でも tuple でも書けるため）。"""
        if not self.file_hint:
            return ()
        if isinstance(self.file_hint, str):
            return (self.file_hint,)
        return tuple(self.file_hint)


