def normalize_school_name(value: object) -> str:
    """設置者の接頭辞を外して学校名を突き合わせ可能にする。

    P29 と東京都教育委員会の在籍者数 CSV は同じ学校を別の書き方で載せる:

        P29            東京都立城南特別支援学校 / 都立城東特別支援学校
        都教委 CSV     城南特別支援学校（設置者は別列）

    「東京都立」と「都立」が P29 の中でも混在しており、接頭辞を外さないと
    39 校中 2 校だけが静かに落ちる。**落ちた学校は既定値 150 人になる**ので、
    出力を眺めても気付けない（normalize_schools が公立の未一致で止める）。
    """
    # **`str(value or "")` にしてはいけない。** 欠測が float('nan') で来ると
    # nan は真なので "nan" が学校名として持ち回られる。normalize_ward で
    # 一度やらかしており（公開中の提言 3 件に「nanの施設」と出た）、
    # ここでは合計行の空の名称がそれに当たる。
    if value is None or (isinstance(value, float) and value != value):
        return ""
    name = re.sub(r"\s|　", "", str(value).strip())
    if name.lower() == "nan":
        return ""
    name = re.sub(r"^(?:東京)?都立", "", name)
    return re.sub(r"^.{1,6}?[区市町村]立", "", name)


