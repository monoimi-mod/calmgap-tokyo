def classify_welfare_by_name(name: str | None) -> tuple[str, bool]:
    """施設名称からサービス種別を推定する。

    Returns
    -------
    (種別名, 推定したか)
        キーワードに当たらなければ ("障害福祉サービス事業所", False) を返す。
    """
    if not name:
        return ("障害福祉サービス事業所", False)
    s = str(name)
    for pattern, kind in WELFARE_NAME_PATTERNS:
        if pattern in s:
            return (kind, True)
    return ("障害福祉サービス事業所", False)


