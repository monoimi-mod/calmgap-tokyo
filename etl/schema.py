def normalize_welfare_type(raw: str | None) -> str:
    """事業所種別の表記を正規化する。"""
    if not raw:
        return ""
    s = str(raw).strip()
    return WELFARE_TYPE_ALIASES.get(s, s)


def welfare_weight(raw: str | None) -> float:
    """事業所種別から需要重みを引く。未知の種別は既定値。"""
    return WELFARE_DEMAND_WEIGHT.get(
        normalize_welfare_type(raw), WELFARE_DEMAND_WEIGHT_DEFAULT
    )


