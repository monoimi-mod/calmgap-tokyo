def host_type(name: str | None, category: str | None = None) -> str | None:
    """施設名（と、あれば種別列）からホスト種別を判定する。該当なしは None。

    **名称で判定できなかったときだけ種別列を見る。** 逆にしないのは、
    除外パターン（駐輪場・公衆便所）が名称にしか現れないため。
    種別列を先に見ると「◯◯駅駐輪場」がカテゴリ「区民施設」で通ってしまう。

    種別列そのものにも除外パターンを当てる（カテゴリ「自転車駐車場」など）。
    """
    s = str(name or "")
    for pattern in HOST_EXCLUDE_PATTERNS + HOST_POLICY_EXCLUDE:
        if pattern in s:
            return None
    for pattern, kind in HOST_TYPE_PATTERNS:
        if pattern in s:
            return kind

    c = str(category or "")
    if not c:
        return None
    for pattern in HOST_EXCLUDE_PATTERNS + HOST_POLICY_EXCLUDE:
        if pattern in c:
            return None
    for pattern, kind in HOST_CATEGORY_PATTERNS + HOST_TYPE_PATTERNS:
        if pattern in c:
            return kind
    return None


