# 診療科目文字列からの抽出キーワード。部分一致で使う。
# 「児童精神科」「老年心療内科」「精神神経科」のような複合名も拾える。
PSYCH_CLINIC_KEYWORDS: tuple[str, ...] = ("精神科", "心療内科", "神経科")

# 診療科目は **略称と正式名称が混在**して入る（実データ P04-20_13 で確認）。
#   歯科 7,790 件 / 歯 2,930 件、内科 6,327 件 / 内 2,710 件
# 精神科は正式名称 1,190 件に対し略称「精」が 301 件、
# 心療内科は 835 件に対し「心内」が 210 件ある。
# 正式名称の部分一致だけで絞ると **2 割前後を静かに取りこぼす**。
#
# 略称は 1〜2 文字で、部分一致にすると別の科を巻き込む
# （「神」は神経内科=「神内」の一部でもある）。区切って完全一致で見る。
# 「神経」は神経内科の略記としても使われ判別できないので入れない
# （取りこぼしても混入させない）。
PSYCH_CLINIC_ABBREV: frozenset[str] = frozenset({"精", "精神", "心内", "神", "児精"})

# 診療科目欄の区切り。全角空白が基本だが「内．婦．放．循内．心療内科」のように
# 中黒・読点で連結された行もある。
DEPARTMENT_SEPARATORS = r"[\s　．・，、,/／|｜]+"


def is_psych_clinic(departments: object) -> bool:
    """診療科目欄が精神科・心療内科を含むか。

    正式名称は部分一致、略称は区切ってからの完全一致で判定する。
    """
    s = str(departments or "")
    if not s:
        return False
    if any(k in s for k in PSYCH_CLINIC_KEYWORDS):
        return True
    return any(
        t in PSYCH_CLINIC_ABBREV for t in re.split(DEPARTMENT_SEPARATORS, s.strip())
    )


