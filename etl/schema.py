# 名称に含まれていたら「人が滞在できる屋内施設ではない」もの。
# 種別判定より先に効かせる。
#
# 渋谷区・世田谷区の公共施設一覧を実際に通して分かったこと:
# 一覧には駐輪場・公衆便所・指定喫煙場所が同じ粒度で載っており、
# 「渋谷駅東口公衆便所」「世田谷駅南自転車等駐車場」がホスト候補に入っていた。
# 供給側が過大になる方向の誤りで、地図上は「到達できている」と見える。
HOST_EXCLUDE_PATTERNS: tuple[str, ...] = (
    "自転車",
    "駐輪",
    "駐車場",
    "レンタサイクル",
    "公衆トイレ",
    "公衆便所",
    "便所",
    "喫煙",
    "倉庫",
    "ポンプ",
    "変電",
    "車庫",
    "集積",
    "返却ポスト",
    "予定地",
    "跡地",
)

# 区市町村の公共施設一覧は様式がバラバラなため、
# 施設名の部分一致でホスト種別へ寄せる。前方から順に判定する。
#
# 「駅」は入れない。区の一覧に載る「◯◯駅…」は駅そのものではなく、
# 駅前の駐輪場・公衆便所・喫煙場所だった（渋谷区で 32 件、世田谷区で 10 件が
# これに当たり、全部がホスト候補に入っていた）。駅を供給側に数えるなら
# 鉄道側のデータで別に扱う。
HOST_TYPE_PATTERNS: tuple[tuple[str, str], ...] = (
    ("図書館", "図書館"),
    ("区民センター", "区民センター"),
    ("区民会館", "区民センター"),
    ("地区会館", "区民センター"),
    ("コミュニティセンター", "区民センター"),
    ("出張所", "出張所"),
    ("区民事務所", "出張所"),
    ("行政サービスコーナー", "出張所"),
    # 世田谷区は出張所を「まちづくりセンター」と呼ぶ。常設の窓口があり、
    # 予約制の貸室（区民集会所・高齢者集会所）とは性質が違うので出張所へ寄せる。
    ("まちづくりセンター", "出張所"),
    ("児童館", "児童館"),
    ("子ども家庭支援センター", "児童館"),
    ("文化センター", "文化施設"),
    ("美術館", "文化施設"),
    ("博物館", "文化施設"),
    ("ホール", "文化施設"),
    ("公園事務所", "公園管理施設"),
    ("公園管理", "公園管理施設"),
)


def host_type(name: str | None) -> str | None:
    """施設名からホスト種別を判定する。該当なしは None。"""
    if not name:
        return None
    s = str(name)
    for pattern in HOST_EXCLUDE_PATTERNS:
        if pattern in s:
            return None
    for pattern, kind in HOST_TYPE_PATTERNS:
        if pattern in s:
            return kind
    return None


